const fs=require('fs'),path=require('path');
module.exports=function verify(root,files,read){
 const names=new Set(files.map(p=>path.relative(root,p).split(path.sep).join('/')));
 for(const file of files.filter(p=>/\.(js|mjs)$/.test(p)&&!p.includes(path.sep+'vendor'+path.sep))){
  const source=read(file).toString();
  for(const match of source.matchAll(/(?:from\s*|import\s*\(\s*|import\s*)['"](\.\.?\/[^'"]+)['"]/g)){
   const target=path.resolve(path.dirname(file),match[1].split('?')[0]);
   const name=path.relative(root,target).split(path.sep).join('/');
   if(name==='resource-manifest.js')continue; // Generated by this build.
   if(!names.has(name))throw Error(`Missing module in classroom package: ${path.relative(root,file)} -> ${match[1]}`);
   read(target); // Also fails when present locally but absent from the publish index.
  }
 }
};
